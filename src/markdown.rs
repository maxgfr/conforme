use anyhow::{bail, Result};

use crate::config::{
    ActivationMode, McpTransport, NormalizedAgent, NormalizedConfig, NormalizedMcpServer,
    NormalizedPlugin, NormalizedRule, NormalizedSkill,
};

/// The metadata keys of each kind of section. `plugin` places a rule, skill,
/// agent or MCP section in the plugin of that name.
const RULE_KEYS: &[&str] = &["activation", "description", "plugin"];
const SKILL_KEYS: &[&str] = &["description", "invocation", "tools", "plugin"];
const AGENT_KEYS: &[&str] = &[
    "description",
    "model",
    "tools",
    "color",
    "permission-mode",
    "plugin",
];
const MCP_KEYS: &[&str] = &[
    "command",
    "args",
    "url",
    "transport",
    "env",
    "headers",
    "plugin",
];
/// A `## Marketplace:` section's source: `github: owner/repo`, `git: <url>`
/// or `directory: <path>`, with `ref` and `path` (a sub-folder), or `source:`
/// the whole source object in JSON (Claude Code's shape).
const MARKETPLACE_KEYS: &[&str] = &["github", "git", "directory", "ref", "path", "source"];
/// A `## Hook:` section: Claude Code's event and tool names; its body is the
/// command (a code block around it is taken off).
const HOOK_KEYS: &[&str] = &["event", "matcher", "timeout", "plugin"];
const PLUGIN_KEYS: &[&str] = &[
    "marketplace",
    "description",
    "version",
    "author",
    "homepage",
    "repository",
    "license",
    "keywords",
    "disabled",
];

const GENERATED_PREFIX: &str = "<!-- Generated by conforme from ";

/// The first line of an AGENTS.md that `sync` generates from a tool source:
/// it names the source, so a source changed by hand afterwards is noticed,
/// and tells whoever reads the file (an agent included) not to edit it.
pub fn generated_marker(source_id: &str) -> String {
    format!(
        "{GENERATED_PREFIX}{source_id}. Edit that tool's config, not this file: every sync rewrites it. -->"
    )
}

/// The source an AGENTS.md was generated from, when its first line is the
/// [`generated_marker`].
pub fn generated_from(content: &str) -> Option<&str> {
    let content = content.strip_prefix('\u{feff}').unwrap_or(content);
    let rest = content.lines().next()?.strip_prefix(GENERATED_PREFIX)?;
    let id = rest.split(['.', ' ']).next()?;
    (!id.is_empty()).then_some(id)
}

/// Parse an AGENTS.md file into a NormalizedConfig.
///
/// Convention:
/// - Text before the first `##` heading becomes `instructions`
/// - `## Rule: <name>` → NormalizedRule with activation comments
/// - `## Skill: <name>` → NormalizedSkill with description/tools comments
/// - `## Agent: <name>` → NormalizedAgent with model/tools comments
/// - `## MCP: <name>` → NormalizedMcpServer with transport comments
/// - `## Plugin: <name>` → NormalizedPlugin with manifest comments, its body
///   the plugin's instructions; a rule, skill, agent or MCP section with a
///   `<!-- plugin: <name> -->` comment belongs to that plugin (declared by
///   its own section or not, before or after it)
pub fn parse_agents_md(content: &str) -> Result<NormalizedConfig> {
    let content = &*crate::config::normalize_text(content);
    let mut config = NormalizedConfig::new();
    let mut current_section: Option<Section> = None;
    let declared = &mut std::collections::HashSet::new();

    let skip = usize::from(generated_from(content).is_some());
    // A heading inside a code fence is text (a documented example of the
    // convention), never a section.
    let mut fence: Option<(char, usize)> = None;
    for line in content.lines().skip(skip) {
        let in_fence = fence.is_some();
        fence = next_fence(fence, line);
        if in_fence || fence.is_some() {
            match &mut current_section {
                Some(section) => section.lines_mut().push(line.to_string()),
                None => {
                    config.instructions.push_str(line);
                    config.instructions.push('\n');
                }
            }
        } else if let Some(name) = line.strip_prefix("## Rule: ") {
            flush_section(&mut config, current_section.take(), declared)?;
            current_section = Some(Section::Rule(name.trim().to_string(), Vec::new()));
        } else if let Some(name) = line.strip_prefix("## Skill: ") {
            flush_section(&mut config, current_section.take(), declared)?;
            current_section = Some(Section::Skill(name.trim().to_string(), Vec::new()));
        } else if let Some(name) = line.strip_prefix("## Agent: ") {
            flush_section(&mut config, current_section.take(), declared)?;
            current_section = Some(Section::Agent(name.trim().to_string(), Vec::new()));
        } else if let Some(name) = line.strip_prefix("## MCP: ") {
            flush_section(&mut config, current_section.take(), declared)?;
            current_section = Some(Section::Mcp(name.trim().to_string(), Vec::new()));
        } else if let Some(name) = line.strip_prefix("## Plugin: ") {
            flush_section(&mut config, current_section.take(), declared)?;
            current_section = Some(Section::Plugin(name.trim().to_string(), Vec::new()));
        } else if let Some(name) = line.strip_prefix("## Marketplace: ") {
            flush_section(&mut config, current_section.take(), declared)?;
            current_section = Some(Section::Marketplace(name.trim().to_string(), Vec::new()));
        } else if let Some(name) = line.strip_prefix("## Hook: ") {
            flush_section(&mut config, current_section.take(), declared)?;
            current_section = Some(Section::Hook(name.trim().to_string(), Vec::new()));
        } else if let Some(section) = &mut current_section {
            section.lines_mut().push(line.to_string());
        } else {
            config.instructions.push_str(line);
            config.instructions.push('\n');
        }
    }

    flush_section(&mut config, current_section.take(), declared)?;
    config.instructions = config.instructions.trim().to_string();

    Ok(config)
}

/// The code fence open after `line`, given the one open before it: a line of
/// three or more backticks or tildes (indented at most three spaces) opens
/// one, and a line of the same character, at least as long and with nothing
/// after it, closes it (CommonMark).
fn next_fence(open: Option<(char, usize)>, line: &str) -> Option<(char, usize)> {
    let indent = line.len() - line.trim_start_matches(' ').len();
    let trimmed = line.trim_start_matches(' ');
    let marker = trimmed.chars().next().filter(|c| *c == '`' || *c == '~');
    let run = marker.map_or(0, |c| trimmed.chars().take_while(|x| *x == c).count());
    match (open, marker) {
        (Some((c, len)), Some(m))
            if indent <= 3 && m == c && run >= len && trimmed[run..].trim().is_empty() =>
        {
            None
        }
        (Some(open), _) => Some(open),
        // A backtick fence's info string holds no backtick (CommonMark).
        (None, Some(m))
            if indent <= 3 && run >= 3 && !(m == '`' && trimmed[run..].contains('`')) =>
        {
            Some((m, run))
        }
        (None, _) => None,
    }
}

/// The source config of a tool that reads `AGENTS.md` (or a fallback)
/// natively: Codex, OpenCode, DeepSeek Harness, Mistral Vibe, Kilo Code.
///
/// The first existing file among `candidates` is parsed with the AGENTS.md
/// convention, so its `## Rule:` sections become rules and do not land in the
/// instructions. Its `## Skill:`, `## Agent:` and `## MCP:` sections are added
/// to what the tool's own files hold (`tool`), which win on a name clash.
/// Sync never regenerates this `AGENTS.md` (see
/// [`crate::adapters::AiToolAdapter::reads_agents_md`]): it is the source.
pub fn read_native_agents_md(
    project_root: &std::path::Path,
    candidates: &[&str],
    tool: NormalizedConfig,
) -> Result<NormalizedConfig> {
    let Some(path) = candidates
        .iter()
        .map(|name| project_root.join(name))
        .find(|path| path.exists())
    else {
        return Ok(tool);
    };
    read_agents_md_files(&[path], tool)
}

/// Like [`read_native_agents_md`], for a tool that loads *every* existing
/// file among `files` (Claude Code loads both `AGENTS.md` and
/// `.claude/AGENTS.md`): their instructions and rules are concatenated in
/// order, a later rule of the same name replacing an earlier one.
pub fn read_agents_md_files(
    files: &[std::path::PathBuf],
    tool: NormalizedConfig,
) -> Result<NormalizedConfig> {
    let mut config = tool;
    let mut instructions = Vec::new();
    let mut rules: Vec<crate::config::NormalizedRule> = Vec::new();
    let mut sections = NormalizedConfig::default();
    for path in files.iter().filter(|path| path.is_file()) {
        let md = parse_agents_md(&crate::config::read_text(path)?)?;
        if !md.instructions.trim().is_empty() {
            instructions.push(md.instructions);
        }
        for rule in md.rules {
            rules.retain(|r| r.name != rule.name);
            rules.push(rule);
        }
        sections.skills.extend(md.skills);
        sections.agents.extend(md.agents);
        sections.mcp_servers.extend(md.mcp_servers);
        sections.plugins.extend(md.plugins);
        sections.plugin_refs.extend(md.plugin_refs);
        sections.marketplaces.extend(md.marketplaces);
        sections.hooks.extend(md.hooks);
    }
    config.instructions = instructions.join("\n\n");
    config.rules = rules;
    let md = sections;
    // Names are compared as written to disk: `## Skill: Deploy App` is the
    // tool's `deploy-app` folder.
    let same =
        |a: &str, b: &str| crate::config::sanitize_name(a) == crate::config::sanitize_name(b);
    for skill in md.skills {
        if !config.skills.iter().any(|s| same(&s.name, &skill.name)) {
            config.skills.push(skill);
        }
    }
    for agent in md.agents {
        if !config.agents.iter().any(|a| same(&a.name, &agent.name)) {
            config.agents.push(agent);
        }
    }
    for server in md.mcp_servers {
        if !config.mcp_servers.iter().any(|s| s.name == server.name) {
            config.mcp_servers.push(server);
        }
    }
    for plugin in md.plugins {
        if !config.plugins.iter().any(|p| same(&p.name, &plugin.name)) {
            config.plugins.push(plugin);
        }
    }
    for plugin in md.plugin_refs {
        if !config.plugin_refs.iter().any(|p| p.id() == plugin.id()) {
            config.plugin_refs.push(plugin);
        }
    }
    for marketplace in md.marketplaces {
        if !config
            .marketplaces
            .iter()
            .any(|m| m.name == marketplace.name)
        {
            config.marketplaces.push(marketplace);
        }
    }
    // The tool's own hooks win over the AGENTS.md ones.
    if config.hooks.is_empty() {
        config.hooks = md.hooks;
    }
    Ok(config)
}

enum Section {
    Rule(String, Vec<String>),
    Skill(String, Vec<String>),
    Agent(String, Vec<String>),
    Mcp(String, Vec<String>),
    Plugin(String, Vec<String>),
    Marketplace(String, Vec<String>),
    Hook(String, Vec<String>),
}

impl Section {
    fn lines_mut(&mut self) -> &mut Vec<String> {
        match self {
            Section::Rule(_, lines)
            | Section::Skill(_, lines)
            | Section::Agent(_, lines)
            | Section::Mcp(_, lines)
            | Section::Plugin(_, lines)
            | Section::Marketplace(_, lines)
            | Section::Hook(_, lines) => lines,
        }
    }
}

/// The plugin a section's `<!-- plugin: <name> -->` comment places it in.
fn section_plugin(lines: &[String], keys: &[&str]) -> Option<String> {
    split_section(lines, keys)
        .0
        .into_iter()
        .find(|(key, _)| key == "plugin")
        .map(|(_, value)| decode_text(value))
        .filter(|name| !name.trim().is_empty())
}

/// The plugin named `name` in `config`, added (with only its name) when no
/// section has declared it yet.
fn plugin_named<'a>(config: &'a mut NormalizedConfig, name: &str) -> &'a mut NormalizedPlugin {
    let key = crate::config::sanitize_name(name);
    let index = match config
        .plugins
        .iter()
        .position(|p| crate::config::sanitize_name(&p.name) == key)
    {
        Some(index) => index,
        None => {
            config.plugins.push(NormalizedPlugin {
                name: name.trim().to_string(),
                ..Default::default()
            });
            config.plugins.len() - 1
        }
    };
    &mut config.plugins[index]
}

/// Add a finished section to `config`. `declared` holds the plugins a
/// `## Plugin:` section has declared: a second one of the same name is kept
/// apart, so the duplicate is reported rather than merged.
fn flush_section(
    config: &mut NormalizedConfig,
    section: Option<Section>,
    declared: &mut std::collections::HashSet<String>,
) -> Result<()> {
    match section {
        Some(Section::Rule(name, lines)) => {
            let rule = build_rule(&name, &lines)?;
            match section_plugin(&lines, RULE_KEYS) {
                Some(plugin) => plugin_named(config, &plugin).rules.push(rule),
                None => config.rules.push(rule),
            }
        }
        Some(Section::Skill(name, lines)) => {
            let skill = build_skill(&name, &lines);
            match section_plugin(&lines, SKILL_KEYS) {
                Some(plugin) => plugin_named(config, &plugin).skills.push(skill),
                None => config.skills.push(skill),
            }
        }
        Some(Section::Agent(name, lines)) => {
            let agent = build_agent(&name, &lines);
            match section_plugin(&lines, AGENT_KEYS) {
                Some(plugin) => plugin_named(config, &plugin).agents.push(agent),
                None => config.agents.push(agent),
            }
        }
        Some(Section::Mcp(name, lines)) => {
            if let Some(mcp) = build_mcp(&name, &lines) {
                match section_plugin(&lines, MCP_KEYS) {
                    Some(plugin) => plugin_named(config, &plugin).mcp_servers.push(mcp),
                    None => config.mcp_servers.push(mcp),
                }
            }
        }
        Some(Section::Plugin(name, lines)) => {
            if name.is_empty() {
                bail!("empty plugin name");
            }
            let (meta, instructions) = split_section(&lines, PLUGIN_KEYS);
            // With a marketplace, the plugin is one the project enables from
            // there, not a bundle it holds.
            if let Some((_, market)) = meta.iter().find(|(key, _)| key == "marketplace") {
                let disabled = meta
                    .iter()
                    .any(|(key, value)| key == "disabled" && value.eq_ignore_ascii_case("true"));
                config.plugin_refs.push(crate::config::NormalizedPluginRef {
                    plugin: name,
                    marketplace: decode_text(market),
                    enabled: !disabled,
                });
                return Ok(());
            }
            let plugin = if declared.insert(crate::config::sanitize_name(&name)) {
                plugin_named(config, &name)
            } else {
                config.plugins.push(NormalizedPlugin {
                    name: name.clone(),
                    ..Default::default()
                });
                config.plugins.last_mut().expect("just pushed")
            };
            plugin.name = name;
            plugin.instructions = instructions;
            for (key, value) in meta {
                match key.as_str() {
                    "description" => plugin.description = decode_text(value),
                    "version" => plugin.version = Some(decode_text(value)),
                    "author" => plugin.author = Some(decode_text(value)),
                    "homepage" => plugin.homepage = Some(decode_text(value)),
                    "repository" => plugin.repository = Some(decode_text(value)),
                    "license" => plugin.license = Some(decode_text(value)),
                    "keywords" => plugin.keywords = decode_list(value),
                    _ => plugin.disabled = value.eq_ignore_ascii_case("true"),
                }
            }
        }
        Some(Section::Hook(name, lines)) => {
            let (meta, body) = split_section(&lines, HOOK_KEYS);
            let get = |k: &str| {
                meta.iter()
                    .find(|(key, _)| key == k)
                    .map(|(_, v)| decode_text(v))
            };
            let Some(event) = get("event") else {
                bail!("hook {name} has no event: add `<!-- event: PreToolUse -->`");
            };
            // The command, inside a code block or not.
            let command = body
                .lines()
                .filter(|l| !l.trim_start().starts_with("```"))
                .collect::<Vec<_>>()
                .join("\n")
                .trim()
                .to_string();
            if command.is_empty() {
                bail!("hook {name} has no command");
            }
            let hook = crate::config::NormalizedHook {
                name,
                event,
                matcher: get("matcher").filter(|m| !m.is_empty() && m != "*"),
                command,
                timeout: get("timeout").and_then(|t| t.parse().ok()),
            };
            match section_plugin(&lines, HOOK_KEYS) {
                Some(plugin) => plugin_named(config, &plugin).hooks.push(hook),
                None => config.hooks.push(hook),
            }
        }
        Some(Section::Marketplace(name, lines)) => {
            if name.is_empty() {
                bail!("empty marketplace name");
            }
            let (meta, _) = split_section(&lines, MARKETPLACE_KEYS);
            let get = |k: &str| {
                meta.iter()
                    .find(|(key, _)| key == k)
                    .map(|(_, v)| decode_text(v))
            };
            let mut source = serde_json::Map::new();
            if let Some(json) = get("source") {
                let parsed: serde_json::Value = serde_json::from_str(&json).map_err(|e| {
                    anyhow::anyhow!("marketplace {name}: `source` is not a JSON object: {e}")
                })?;
                let serde_json::Value::Object(object) = parsed else {
                    bail!("marketplace {name}: `source` is not a JSON object");
                };
                source = object;
            } else if let Some(repo) = get("github") {
                source.insert("source".into(), "github".into());
                source.insert("repo".into(), repo.into());
            } else if let Some(url) = get("git") {
                source.insert("source".into(), "git".into());
                source.insert("url".into(), url.into());
            } else if let Some(path) = get("directory") {
                source.insert("source".into(), "directory".into());
                source.insert("path".into(), path.into());
            } else {
                bail!("marketplace {name} has no source: add `<!-- github: owner/repo -->`, `<!-- git: <url> -->` or `<!-- directory: <path> -->`");
            }
            if get("source").is_none() {
                for key in ["ref", "path"] {
                    if let Some(value) = get(key).filter(|_| get("directory").is_none()) {
                        source.insert(key.into(), value.into());
                    }
                }
            }
            config
                .marketplaces
                .push(crate::config::NormalizedMarketplace {
                    name,
                    source: serde_json::Value::Object(source),
                });
        }
        None => {}
    }
    Ok(())
}

/// A metadata comment, `<!-- key: value -->` with any spacing and any case of
/// the key.
fn meta_comment(line: &str) -> Option<(String, &str)> {
    let inner = line.trim().strip_prefix("<!--")?.strip_suffix("-->")?;
    let (key, value) = inner.split_once(':')?;
    let key = key.trim();
    let is_key = !key.is_empty() && key.chars().all(|c| c.is_ascii_alphanumeric() || c == '-');
    is_key.then(|| (key.to_ascii_lowercase(), value.trim()))
}

/// A section's metadata and its body. Metadata is read only from the comment
/// lines right after the heading (blank lines between them allowed), and only
/// for the `keys` that kind of section has: the same comment further down, in
/// a code example for instance, is text.
fn split_section<'a>(lines: &'a [String], keys: &[&str]) -> (Vec<(String, &'a str)>, String) {
    let mut meta = Vec::new();
    let mut body_start = lines.len();
    for (i, line) in lines.iter().enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        match meta_comment(line) {
            Some((key, value)) if keys.contains(&key.as_str()) => meta.push((key, value)),
            _ => {
                body_start = i;
                break;
            }
        }
    }
    let body = lines[body_start..].join("\n").trim().to_string();
    (meta, body)
}

/// Whether a value must be written in its JSON form to read back as is.
fn needs_json(value: &str) -> bool {
    value.contains(['\n', '\r']) || value.contains("-->") || value != value.trim()
}

/// A value in JSON, with `-->` escaped so it cannot end the comment.
fn to_json<T: serde::Serialize + ?Sized>(value: &T) -> String {
    serde_json::to_string(value)
        .unwrap_or_default()
        .replace("-->", "--\\u003e")
}

/// A text value: as written, or in JSON (`"line 1\nline 2"`) when plain text
/// would not read back the same.
fn encode_text(value: &str) -> String {
    if needs_json(value) || value.starts_with('"') {
        to_json(value)
    } else {
        value.to_string()
    }
}

fn decode_text(value: &str) -> String {
    if value.starts_with('"') {
        if let Ok(text) = serde_json::from_str::<String>(value) {
            return text;
        }
    }
    value.to_string()
}

/// A list value: `a, b`, or `["a,b", "c"]` when an item holds a comma, is
/// empty or padded, or would not read back as is.
fn encode_list(items: &[String]) -> String {
    let plain = !items.first().is_some_and(|i| i.starts_with('['))
        && items
            .iter()
            .all(|i| !i.is_empty() && !i.contains(',') && !needs_json(i));
    if plain {
        items.join(", ")
    } else {
        to_json(items)
    }
}

fn decode_list(value: &str) -> Vec<String> {
    if value.starts_with('[') {
        if let Ok(items) = serde_json::from_str::<Vec<String>>(value) {
            return items;
        }
    }
    value
        .split(',')
        .map(|s| s.trim().to_string())
        .filter(|s| !s.is_empty())
        .collect()
}

/// A map value: `K=v, L=w`, or `{"K":"a,b"}` when a key or value would not
/// read back as is.
fn encode_map(map: &std::collections::BTreeMap<String, String>) -> String {
    let plain = !map.keys().next().is_some_and(|k| k.starts_with('{'))
        && map.iter().all(|(k, v)| {
            !k.is_empty()
                && !k.contains([',', '='])
                && !v.contains(',')
                && !needs_json(k)
                && !needs_json(v)
        });
    if plain {
        map.iter()
            .map(|(k, v)| format!("{k}={v}"))
            .collect::<Vec<_>>()
            .join(", ")
    } else {
        to_json(map)
    }
}

fn decode_map(value: &str) -> std::collections::BTreeMap<String, String> {
    if value.starts_with('{') {
        if let Ok(map) = serde_json::from_str(value) {
            return map;
        }
    }
    value
        .split(',')
        .filter_map(|pair| pair.trim().split_once('='))
        .map(|(k, v)| (k.trim().to_string(), v.trim().to_string()))
        .collect()
}

fn build_rule(name: &str, lines: &[String]) -> Result<NormalizedRule> {
    let (meta, content) = split_section(lines, RULE_KEYS);
    let mut activation = ActivationMode::Always;
    let mut description: Option<String> = None;
    for (key, value) in meta {
        match key.as_str() {
            "activation" => activation = parse_activation(value)?,
            "plugin" => {}
            _ => description = Some(decode_text(value)),
        }
    }

    if let Some(desc) = description {
        if matches!(activation, ActivationMode::AgentDecision { .. }) {
            activation = ActivationMode::AgentDecision { description: desc };
        }
    }

    if name.is_empty() {
        bail!("empty rule name");
    }

    Ok(NormalizedRule {
        name: name.to_string(),
        content,
        activation,
    })
}

fn build_skill(name: &str, lines: &[String]) -> NormalizedSkill {
    let (meta, content) = split_section(lines, SKILL_KEYS);
    let mut skill = NormalizedSkill {
        name: name.to_string(),
        content,
        ..Default::default()
    };
    for (key, value) in meta {
        match key.as_str() {
            "description" => skill.description = decode_text(value),
            "invocation" => skill.manual_invocation = value.eq_ignore_ascii_case("manual"),
            "plugin" => {}
            _ => skill.allowed_tools = decode_list(value),
        }
    }
    skill
}

fn build_agent(name: &str, lines: &[String]) -> NormalizedAgent {
    let (meta, content) = split_section(lines, AGENT_KEYS);
    let mut agent = NormalizedAgent {
        name: name.to_string(),
        content,
        ..Default::default()
    };
    for (key, value) in meta {
        match key.as_str() {
            "description" => agent.description = decode_text(value),
            "model" => agent.model = Some(decode_text(value)),
            "tools" => agent.tools = decode_list(value),
            "color" => agent.color = Some(decode_text(value)),
            "plugin" => {}
            _ => agent.permission_mode = Some(decode_text(value)),
        }
    }
    agent
}

fn build_mcp(name: &str, lines: &[String]) -> Option<NormalizedMcpServer> {
    let (meta, _) = split_section(lines, MCP_KEYS);
    let mut command = None;
    let mut args = Vec::new();
    let mut url = None;
    let mut env = std::collections::BTreeMap::new();
    let mut headers = std::collections::BTreeMap::new();
    let mut transport_kind: Option<String> = None;
    for (key, value) in meta {
        match key.as_str() {
            "command" => command = Some(decode_text(value)),
            "args" => args = decode_list(value),
            "url" => url = Some(decode_text(value)),
            "transport" => transport_kind = Some(value.to_ascii_lowercase()),
            "env" => env.extend(decode_map(value)),
            "plugin" => {}
            _ => headers.extend(decode_map(value)),
        }
    }

    // A `## MCP:` section without either a `url:` or a `command:` comment does
    // not describe a usable server, so it is skipped rather than emitted empty.
    let transport = if let Some(u) = url {
        if transport_kind.as_deref() == Some("sse") {
            McpTransport::Sse { url: u, headers }
        } else {
            McpTransport::Http { url: u, headers }
        }
    } else {
        McpTransport::Stdio {
            command: command?,
            args,
        }
    };

    Some(NormalizedMcpServer {
        name: name.to_string(),
        transport,
        env,
    })
}

fn parse_activation(s: &str) -> Result<ActivationMode> {
    let s = s.trim();
    let (mode, rest) = s.split_once(char::is_whitespace).unwrap_or((s, ""));
    let mode = mode.to_ascii_lowercase();
    if mode == "always" {
        Ok(ActivationMode::Always)
    } else if mode == "manual" {
        Ok(ActivationMode::Manual)
    } else if mode == "agent-decision" {
        Ok(ActivationMode::AgentDecision {
            description: String::new(),
        })
    } else if let Some(globs) = (mode == "glob").then_some(rest) {
        let patterns = crate::config::split_globs(globs);
        if patterns.is_empty() {
            bail!("glob activation requires at least one pattern");
        }
        Ok(ActivationMode::GlobMatch(patterns))
    } else {
        bail!("unknown activation mode: {}", s)
    }
}

/// Generate a template AGENTS.md file.
pub fn template_agents_md() -> String {
    r#"# Project Instructions

<!-- Add your project-wide instructions here. -->
<!-- conforme will sync this file to all detected AI coding tools. -->

## Rule: General Conventions
<!-- activation: always -->

<!-- Add conventions that should always apply. -->
"#
    .to_string()
}

/// Push `text` and a line end, closing a code fence it leaves open: the
/// parser reads every later line inside an open fence as text, so the next
/// `## Rule:` heading and all that follows would land in this section.
fn push_section_text(out: &mut String, text: &str) {
    out.push_str(text);
    out.push('\n');
    if let Some((marker, len)) = text.lines().fold(None, next_fence) {
        out.push_str(&marker.to_string().repeat(len));
        out.push('\n');
    }
}

/// Export a NormalizedConfig back to AGENTS.md format.
pub fn export_as_agents_md(config: &NormalizedConfig) -> String {
    let mut out = String::new();

    if !config.instructions.is_empty() {
        // Instructions read back from an exported file already start with
        // their title; adding another on every export would stack them.
        if !config.instructions.starts_with("# ") {
            out.push_str("# Project Instructions\n\n");
        }
        push_section_text(&mut out, &config.instructions);
    }

    for rule in &config.rules {
        export_rule(&mut out, rule, None);
    }
    for skill in &config.skills {
        export_skill(&mut out, skill, None);
    }
    for agent in &config.agents {
        export_agent(&mut out, agent, None);
    }
    for mcp in &config.mcp_servers {
        export_mcp(&mut out, mcp, None);
    }
    for plugin in &config.plugins {
        export_plugin(&mut out, plugin);
    }
    for plugin in &config.plugin_refs {
        out.push_str(&format!("\n## Plugin: {}\n", plugin.plugin));
        out.push_str(&format!(
            "<!-- marketplace: {} -->\n",
            encode_text(&plugin.marketplace)
        ));
        if !plugin.enabled {
            out.push_str("<!-- disabled: true -->\n");
        }
    }
    for marketplace in &config.marketplaces {
        export_marketplace(&mut out, marketplace);
    }
    for hook in &config.hooks {
        export_hook(&mut out, hook, None);
    }

    out
}

/// The `<!-- plugin: <name> -->` line that places a section in a plugin.
fn push_plugin_comment(out: &mut String, plugin: Option<&str>) {
    if let Some(plugin) = plugin {
        out.push_str(&format!("<!-- plugin: {} -->\n", encode_text(plugin)));
    }
}

/// A `## Plugin:` section (manifest metadata, then the plugin's
/// instructions), followed by its components, each naming the plugin.
/// A `## Hook:` section, its command in a code block.
fn export_hook(out: &mut String, hook: &crate::config::NormalizedHook, plugin: Option<&str>) {
    out.push_str(&format!("\n## Hook: {}\n", hook.name));
    push_plugin_comment(out, plugin);
    out.push_str(&format!("<!-- event: {} -->\n", encode_text(&hook.event)));
    if let Some(matcher) = &hook.matcher {
        out.push_str(&format!("<!-- matcher: {} -->\n", encode_text(matcher)));
    }
    if let Some(timeout) = hook.timeout {
        out.push_str(&format!("<!-- timeout: {timeout} -->\n"));
    }
    out.push_str(&format!("\n```sh\n{}\n```\n", hook.command));
}

/// A `## Marketplace:` section: a GitHub, Git or directory source in its own
/// comments when that is all it holds, else the whole source in JSON.
fn export_marketplace(out: &mut String, marketplace: &crate::config::NormalizedMarketplace) {
    out.push_str(&format!("\n## Marketplace: {}\n", marketplace.name));
    let source = marketplace.source.as_object();
    let field = |k: &str| {
        source
            .and_then(|s| s.get(k))
            .and_then(serde_json::Value::as_str)
    };
    let keys: Vec<&str> = source
        .map(|s| s.keys().map(String::as_str).collect())
        .unwrap_or_default();
    let fits = |allowed: &[&str]| keys.iter().all(|k| allowed.contains(k));
    let simple = match field("source") {
        Some("github") if fits(&["source", "repo", "ref", "path"]) => {
            field("repo").map(|repo| ("github", repo))
        }
        Some("git") if fits(&["source", "url", "ref", "path"]) => {
            field("url").map(|url| ("git", url))
        }
        Some("directory") if fits(&["source", "path"]) => {
            field("path").map(|path| ("directory", path))
        }
        _ => None,
    };
    match simple {
        Some((kind, value)) => {
            out.push_str(&format!("<!-- {kind}: {} -->\n", encode_text(value)));
            if kind != "directory" {
                for key in ["ref", "path"] {
                    if let Some(value) = field(key) {
                        out.push_str(&format!("<!-- {key}: {} -->\n", encode_text(value)));
                    }
                }
            }
        }
        None => out.push_str(&format!(
            "<!-- source: {} -->\n",
            encode_text(&serde_json::to_string(&marketplace.source).unwrap_or_default())
        )),
    }
}

fn export_plugin(out: &mut String, plugin: &NormalizedPlugin) {
    out.push_str(&format!("\n## Plugin: {}\n", plugin.name));
    let text = [
        (
            "description",
            Some(&plugin.description).filter(|d| !d.is_empty()),
        ),
        ("version", plugin.version.as_ref()),
        ("author", plugin.author.as_ref()),
        ("homepage", plugin.homepage.as_ref()),
        ("repository", plugin.repository.as_ref()),
        ("license", plugin.license.as_ref()),
    ];
    for (key, value) in text {
        if let Some(value) = value {
            out.push_str(&format!("<!-- {key}: {} -->\n", encode_text(value)));
        }
    }
    if !plugin.keywords.is_empty() {
        out.push_str(&format!(
            "<!-- keywords: {} -->\n",
            encode_list(&plugin.keywords)
        ));
    }
    if plugin.disabled {
        out.push_str("<!-- disabled: true -->\n");
    }
    if !plugin.instructions.is_empty() {
        out.push('\n');
        push_section_text(out, &plugin.instructions);
    }
    let name = Some(plugin.name.as_str());
    for rule in &plugin.rules {
        export_rule(out, rule, name);
    }
    for skill in &plugin.skills {
        export_skill(out, skill, name);
    }
    for agent in &plugin.agents {
        export_agent(out, agent, name);
    }
    for mcp in &plugin.mcp_servers {
        export_mcp(out, mcp, name);
    }
    for hook in &plugin.hooks {
        export_hook(out, hook, name);
    }
}

fn export_rule(out: &mut String, rule: &NormalizedRule, plugin: Option<&str>) {
    out.push_str(&format!("\n## Rule: {}\n", rule.name));
    push_plugin_comment(out, plugin);
    match &rule.activation {
        ActivationMode::Always => {
            out.push_str("<!-- activation: always -->\n");
        }
        ActivationMode::GlobMatch(globs) => {
            out.push_str(&format!("<!-- activation: glob {} -->\n", globs.join(",")));
        }
        ActivationMode::AgentDecision { description } => {
            out.push_str("<!-- activation: agent-decision -->\n");
            if !description.is_empty() {
                out.push_str(&format!(
                    "<!-- description: {} -->\n",
                    encode_text(description)
                ));
            }
        }
        ActivationMode::Manual => {
            out.push_str("<!-- activation: manual -->\n");
        }
    }
    out.push('\n');
    push_section_text(out, &rule.content);
}

fn export_skill(out: &mut String, skill: &NormalizedSkill, plugin: Option<&str>) {
    out.push_str(&format!("\n## Skill: {}\n", skill.name));
    push_plugin_comment(out, plugin);
    if !skill.description.is_empty() {
        out.push_str(&format!(
            "<!-- description: {} -->\n",
            encode_text(&skill.description)
        ));
    }
    if skill.manual_invocation {
        out.push_str("<!-- invocation: manual -->\n");
    }
    if !skill.allowed_tools.is_empty() {
        out.push_str(&format!(
            "<!-- tools: {} -->\n",
            encode_list(&skill.allowed_tools)
        ));
    }
    out.push('\n');
    push_section_text(out, &skill.content);
}

fn export_agent(out: &mut String, agent: &NormalizedAgent, plugin: Option<&str>) {
    out.push_str(&format!("\n## Agent: {}\n", agent.name));
    push_plugin_comment(out, plugin);
    if !agent.description.is_empty() {
        out.push_str(&format!(
            "<!-- description: {} -->\n",
            encode_text(&agent.description)
        ));
    }
    if let Some(model) = &agent.model {
        out.push_str(&format!("<!-- model: {} -->\n", encode_text(model)));
    }
    if !agent.tools.is_empty() {
        out.push_str(&format!("<!-- tools: {} -->\n", encode_list(&agent.tools)));
    }
    if let Some(color) = &agent.color {
        out.push_str(&format!("<!-- color: {} -->\n", encode_text(color)));
    }
    if let Some(permission_mode) = &agent.permission_mode {
        out.push_str(&format!(
            "<!-- permission-mode: {} -->\n",
            encode_text(permission_mode)
        ));
    }
    out.push('\n');
    push_section_text(out, &agent.content);
}

fn export_mcp(out: &mut String, mcp: &NormalizedMcpServer, plugin: Option<&str>) {
    out.push_str(&format!("\n## MCP: {}\n", mcp.name));
    push_plugin_comment(out, plugin);
    match &mcp.transport {
        McpTransport::Stdio { command, args } => {
            out.push_str(&format!("<!-- command: {} -->\n", encode_text(command)));
            if !args.is_empty() {
                out.push_str(&format!("<!-- args: {} -->\n", encode_list(args)));
            }
        }
        McpTransport::Http { url, headers } | McpTransport::Sse { url, headers } => {
            out.push_str(&format!("<!-- url: {} -->\n", encode_text(url)));
            if matches!(&mcp.transport, McpTransport::Sse { .. }) {
                out.push_str("<!-- transport: sse -->\n");
            }
            if !headers.is_empty() {
                out.push_str(&format!("<!-- headers: {} -->\n", encode_map(headers)));
            }
        }
    }
    if !mcp.env.is_empty() {
        out.push_str(&format!("<!-- env: {} -->\n", encode_map(&mcp.env)));
    }
    out.push('\n');
}

