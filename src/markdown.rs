    #[test]
    fn test_parse_mcp_http() {
        let content = "## MCP: github\n<!-- url: https://api.github.com/mcp -->\n<!-- headers: Authorization=Bearer ${GH_TOKEN}, X-Org=acme -->\n\n";
        let config = parse_agents_md(content).unwrap();
        assert_eq!(config.mcp_servers.len(), 1);
        assert!(matches!(
            &config.mcp_servers[0].transport,
            McpTransport::Http { url, headers }
                if url == "https://api.github.com/mcp"
                    && headers["Authorization"] == "Bearer ${GH_TOKEN}"
                    && headers["X-Org"] == "acme"
        ));
        // Headers survive the AGENTS.md export (they were dropped before).
        let exported = export_as_agents_md(&config);
        assert!(
            exported.contains("<!-- headers: Authorization=Bearer ${GH_TOKEN}, X-Org=acme -->"),
            "{exported}"
        );
    }

    #[test]
    fn test_export_parse_export_is_stable() {
        // A tool that reads AGENTS.md natively re-reads the exported file on
        // the next sync; a second export must not add a second title.
        let config = NormalizedConfig {
            instructions: "Be helpful.".to_string(),
            rules: vec![crate::config::NormalizedRule {
                name: "TS".to_string(),
                content: "Use TS.".to_string(),
                activation: ActivationMode::GlobMatch(vec!["src/*.{ts,tsx}".to_string()]),
            }],
            ..Default::default()
        };
        let once = export_as_agents_md(&config);
        let twice = export_as_agents_md(&parse_agents_md(&once).unwrap());
        assert_eq!(once, twice);
    }

    #[test]
    fn test_parse_mcp_without_command_or_url_is_skipped() {
        // A `## MCP:` section that declares neither `command:` nor `url:` cannot
        // describe a usable server, so it must be dropped rather than emitted
        // as a stdio server with an empty command.
        let content = "## MCP: broken\n<!-- args: -y, @mcp/thing -->\n\n";
        let config = parse_agents_md(content).unwrap();
        assert!(config.mcp_servers.is_empty());
    }

    #[test]
    fn test_parse_mcp_url_wins_over_command() {
        // When both are present the HTTP transport takes precedence.
        let content =
            "## MCP: both\n<!-- url: https://example.com/mcp -->\n<!-- command: npx -->\n\n";
        let config = parse_agents_md(content).unwrap();
        assert_eq!(config.mcp_servers.len(), 1);
        assert!(matches!(
            &config.mcp_servers[0].transport,
            McpTransport::Http { url, .. } if url == "https://example.com/mcp"
        ));
    }

    #[test]
    fn test_sse_server_round_trips_through_agents_md() {
        // The legacy HTTP+SSE transport survives an AGENTS.md export: the
        // exported file parses back to the same server.
        let content = "## MCP: legacy\n<!-- url: https://x.dev/sse -->\n<!-- transport: sse -->\n";
        let config = parse_agents_md(content).unwrap();
        assert!(matches!(
            &config.mcp_servers[0].transport,
            McpTransport::Sse { url, .. } if url == "https://x.dev/sse"
        ));
        let exported = export_as_agents_md(&config);
        let reparsed = parse_agents_md(&exported).unwrap();
        assert_eq!(reparsed.mcp_servers, config.mcp_servers);
    }
