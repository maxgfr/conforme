//! Plugin bundles: a named package of rules, skills, agents and MCP servers
//! (see [`NormalizedPlugin`]).
//!
//! A tool that loads a bundle committed in the project (Claude Code, Mistral
//! Vibe, Antigravity CLI) gets one per plugin in its own format, described by
//! a [`PluginShape`]; any other tool gets the plugin's content as its own
//! rules, skills, agents and MCP servers ([`flatten`]).

use anyhow::{bail, Result};
use std::collections::{BTreeMap, HashSet};
use std::path::{Path, PathBuf};

use crate::config::{
    rule_file_name, sanitize_name, ActivationMode, NormalizedConfig, NormalizedPlugin,
    NormalizedRule,
};

/// Marks a plugin bundle folder conforme generated: kept in step with the
/// source and deleted when the plugin leaves it. A bundle folder without it
/// was written by hand and is never adopted, rewritten nor deleted.
pub const PLUGIN_MARKER: &str = ".conforme-plugin";

const PLUGIN_MARKER_CONTENT: &str =
    "This plugin bundle is a copy generated by conforme from the source config.\n\
Edit the plugin in the source; conforme deletes this copy when the plugin leaves the source.\n";

/// The `$schema` an Agent Plugins 1.0 `plugin.json` carries (Mistral Vibe
/// accepts no other: https://docs.mistral.ai/vibe/code/cli/plugins).
pub const AGENT_PLUGINS_SCHEMA: &str = "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json";

/// The schema of an Antigravity `plugin.json`
/// (https://antigravity.google/schemas/v1/plugin.json).
const ANTIGRAVITY_SCHEMA: &str = "https://antigravity.google/schemas/v1/plugin.json";

/// A tool's plugin bundle format.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BundleFormat {
    /// Claude Code: `.claude-plugin/plugin.json`, `skills/`, `commands/`,
    /// `agents/*.md`, `.mcp.json` (https://code.claude.com/docs/en/plugins-reference).
    Claude,
    /// Mistral Vibe: Agent Plugins 1.0 `plugin.json` (strict), `skills/`,
    /// `mcp.json`, `ai.mistral.vibe/agents/*.toml`.
    Vibe,
    /// Antigravity CLI: `plugin.json` (or `.antigravity-plugin/plugin.json`),
    /// `skills/`, `agents/*.md`, `rules/` (`rules/AGENTS.md` always on),
    /// `mcp_config.json` (https://antigravity.google/docs/build-plugins/).
    Antigravity,
    /// Codex: Agent Plugins 1.0 `plugin.json` (`.codex-plugin/plugin.json`
    /// read too), `skills/`, `mcp.json`; no subagents nor rules
    /// (https://developers.openai.com/plugins/build/plugins).
    Codex,
}

/// Where and how a tool keeps the plugin bundles committed in a project.
pub struct PluginShape {
    /// The directory holding one folder per bundle, relative to the project
    /// root.
    pub dir: &'static str,
    pub format: BundleFormat,
}

/// Claude Code loads a folder of `.claude/skills/` holding
/// `.claude-plugin/plugin.json` as the plugin `<name>@skills-dir`, after the
/// project trust check (https://code.claude.com/docs/en/plugins/loading.md).
pub const CLAUDE_PLUGINS: PluginShape = PluginShape {
    dir: ".claude/skills",
    format: BundleFormat::Claude,
};

/// Mistral Vibe loads `.vibe/plugins/<plugin>/` in a trusted folder
/// (https://docs.mistral.ai/vibe/code/cli/plugins).
pub const VIBE_PLUGINS: PluginShape = PluginShape {
    dir: ".vibe/plugins",
    format: BundleFormat::Vibe,
};

/// Antigravity CLI loads `.agents/plugins/<plugin>/`
/// (https://antigravity.google/docs/customization-discovery).
pub const ANTIGRAVITY_PLUGINS: PluginShape = PluginShape {
    dir: ".agents/plugins",
    format: BundleFormat::Antigravity,
};

/// Codex installs the plugins a repository marketplace lists
/// (`.agents/plugins/marketplace.json`) and its project `.codex/config.toml`
/// enables; conforme keeps their bundles in `.codex/plugins/<plugin>/`, a
/// folder Codex gives no other meaning (its plugin cache lives in
/// `$CODEX_HOME/plugins/cache/`).
pub const CODEX_PLUGINS: PluginShape = PluginShape {
    dir: ".codex/plugins",
    format: BundleFormat::Codex,
};

/// Every manifest location a bundle folder may use, any tool.
const MANIFESTS: &[&str] = &[
    ".claude-plugin/plugin.json",
    "plugin.json",
    ".antigravity-plugin/plugin.json",
    ".gemini-plugin/plugin.json",
    ".codex-plugin/plugin.json",
];

/// Whether `dir` is a plugin bundle folder: it holds a plugin manifest.
pub fn is_bundle_dir(dir: &Path) -> bool {
    MANIFESTS.iter().any(|m| dir.join(m).is_file())
}

impl PluginShape {
    /// The directory holding the bundles.
    pub fn root(&self, project_root: &Path) -> PathBuf {
        join_rel(project_root, self.dir)
    }

    /// Whether a bundle holds the plugin's rules and instructions; only
    /// Antigravity's does, so the others get them as their own rules.
    pub fn holds_rules(&self) -> bool {
        self.format == BundleFormat::Antigravity
    }

    /// Whether a bundle holds the plugin's subagents; Codex's does not, so
    /// Codex gets them as its own agents.
    pub fn holds_agents(&self) -> bool {
        self.format != BundleFormat::Codex
    }

    /// Whether a bundle holds the plugin's hooks; Codex's does not (its
    /// `plugin_hooks` feature is `removed` in Codex CLI 0.167.2, `codex
    /// features list`).
    pub fn holds_hooks(&self) -> bool {
        self.format != BundleFormat::Codex
    }

    /// The manifest conforme writes, relative to the bundle folder.
    fn manifest(&self) -> &'static str {
        match self.format {
            BundleFormat::Claude => ".claude-plugin/plugin.json",
            BundleFormat::Vibe | BundleFormat::Antigravity | BundleFormat::Codex => "plugin.json",
        }
    }

    /// The manifests the tool reads, first match wins.
    fn manifests_read(&self) -> &'static [&'static str] {
        match self.format {
            BundleFormat::Claude => &[".claude-plugin/plugin.json"],
            BundleFormat::Vibe => &["plugin.json"],
            // "Existing `.codex-plugin/plugin.json` files remain supported as
            // a compatibility fallback."
            BundleFormat::Codex => &["plugin.json", ".codex-plugin/plugin.json"],
            BundleFormat::Antigravity => &[
                ".antigravity-plugin/plugin.json",
                ".gemini-plugin/plugin.json",
                "plugin.json",
            ],
        }
    }

    /// Paths inside a bundle that hold its components (or its manifest), so
    /// none is one of its loose files.
    fn component_paths(&self) -> &'static [&'static str] {
        match self.format {
            BundleFormat::Claude => &[
                ".claude-plugin",
                "skills",
                "commands",
                "agents",
                ".mcp.json",
                "hooks/hooks.json",
                // A root skill beside the manifest is a plain skill too.
                "SKILL.md",
                crate::skills::SKILL_MARKER,
            ],
            BundleFormat::Vibe => &[
                "plugin.json",
                "skills",
                "mcp.json",
                "ai.mistral.vibe/agents",
                "ai.mistral.vibe/hooks.toml",
            ],
            BundleFormat::Antigravity => &[
                ".antigravity-plugin",
                ".gemini-plugin",
                "plugin.json",
                "skills",
                "agents",
                "rules",
                "mcp_config.json",
                "hooks.json",
            ],
            BundleFormat::Codex => &["plugin.json", ".codex-plugin", "skills", "mcp.json"],
        }
    }
}

/// `rel` (`/`-separated) under `base`.
fn join_rel(base: &Path, rel: &str) -> PathBuf {
    rel.split('/')
        .fold(base.to_path_buf(), |dir, part| dir.join(part))
}

/// A bundle folder that exists, holds something and lacks conforme's marker:
/// written by hand, so never written over.
pub fn is_hand_written_bundle(bundle: &Path) -> bool {
    bundle.is_dir()
        && !bundle.join(PLUGIN_MARKER).is_file()
        && std::fs::read_dir(bundle).is_ok_and(|mut entries| entries.next().is_some())
}

/// The bundle folder of `plugin` in a tool of this shape.
pub fn bundle_dir(project_root: &Path, shape: &PluginShape, plugin: &str) -> PathBuf {
    shape.root(project_root).join(sanitize_name(plugin))
}

/// The config as a tool of `shape` gets it: with no shape, every plugin
/// flattened ([`flatten`]); with one, the plugins stay, holding what the
/// tool's bundle can hold, and only the rest (the rules and instructions of a
/// bundle that has none) is flattened. Applying it twice changes nothing.
pub fn flatten_for(
    config: &NormalizedConfig,
    shape: Option<&PluginShape>,
) -> Result<(NormalizedConfig, Vec<String>)> {
    let Some(shape) = shape else {
        return flatten(config);
    };
    if config.plugins.is_empty() {
        return Ok((config.clone(), Vec::new()));
    }
    let holds_rules = shape.holds_rules();
    let holds_agents = shape.holds_agents();
    let holds_hooks = shape.holds_hooks();
    let unheld = NormalizedConfig {
        plugins: config
            .plugins
            .iter()
            .map(|p| NormalizedPlugin {
                instructions: if holds_rules {
                    String::new()
                } else {
                    p.instructions.clone()
                },
                rules: if holds_rules {
                    Vec::new()
                } else {
                    p.rules.clone()
                },
                skills: Vec::new(),
                agents: if holds_agents {
                    Vec::new()
                } else {
                    p.agents.clone()
                },
                mcp_servers: Vec::new(),
                hooks: if holds_hooks {
                    Vec::new()
                } else {
                    p.hooks.clone()
                },
                files: BTreeMap::new(),
                ..p.clone()
            })
            .collect(),
        ..config.clone()
    };
    // What flattening the rules loses is the same as for a tool without
    // bundles, already reported for the source: only what is particular to
    // this shape is returned.
    let (mut out, _) = flatten(&unheld)?;
    let mut warnings = Vec::new();
    let skill_folders: HashSet<String> =
        out.skills.iter().map(|s| sanitize_name(&s.name)).collect();
    out.plugins = config
        .plugins
        .iter()
        .filter(|p| {
            // Claude Code keeps skills and bundles in the same directory: a
            // skill of the plugin's name holds that folder.
            let clash = shape.format == BundleFormat::Claude
                && skill_folders.contains(&sanitize_name(&p.name));
            if clash {
                warnings.push(format!(
                    "plugin {} is not written: the skill {} already holds .claude/skills/{}; \
                     rename one of them",
                    p.name,
                    sanitize_name(&p.name),
                    sanitize_name(&p.name)
                ));
            }
            !clash
        })
        .map(|p| {
            let mut held = p.clone();
            if !holds_rules {
                held.instructions.clear();
                held.rules.clear();
            }
            if !holds_agents {
                held.agents.clear();
            }
            if !holds_hooks {
                held.hooks.clear();
            }
            held
        })
        .collect();
    Ok((out, warnings))
}

/// Every file under `dir`, recursively, without following a linked
/// directory.
fn files_under(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut found = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(dir) = stack.pop() {
        for path in std::fs::read_dir(&dir)?
            .filter_map(|e| e.ok())
            .map(|e| e.path())
        {
            if path.is_dir() {
                if crate::adapters::is_real_dir(&path) {
                    stack.push(path);
                }
            } else if path.is_file() {
                found.push(path);
            }
        }
    }
    found.sort();
    Ok(found)
}

/// The files of a bundle folder conforme generated ([`PLUGIN_MARKER`]) that
/// the current output does not expect: all of them once its plugin left the
/// source, else those the source no longer has. A folder without the marker
/// is the user's: nothing in it is ever stale.
pub(crate) fn stale_bundle_files(
    folder: &Path,
    expected: &HashSet<PathBuf>,
) -> Result<Vec<PathBuf>> {
    if !folder.join(PLUGIN_MARKER).is_file() {
        return Ok(Vec::new());
    }
    Ok(files_under(folder)?
        .into_iter()
        .filter(|path| !expected.contains(path))
        .collect())
}

/// A JSON object of the manifest metadata every format shares.
fn manifest_metadata(
    plugin: &NormalizedPlugin,
    author_object: bool,
) -> serde_json::Map<String, serde_json::Value> {
    use serde_json::Value;
    let mut manifest = serde_json::Map::new();
    manifest.insert("name".into(), Value::String(sanitize_name(&plugin.name)));
    let mut text = |key: &str, value: Option<&String>| {
        if let Some(value) = value.filter(|v| !v.is_empty()) {
            manifest.insert(key.into(), Value::String(value.clone()));
        }
    };
    text("description", Some(&plugin.description));
    text("version", plugin.version.as_ref());
    text("homepage", plugin.homepage.as_ref());
    text("repository", plugin.repository.as_ref());
    text("license", plugin.license.as_ref());
    if let Some(author) = plugin.author.as_ref().filter(|a| !a.is_empty()) {
        let author = if author_object {
            serde_json::json!({ "name": author })
        } else {
            Value::String(author.clone())
        };
        manifest.insert("author".into(), author);
    }
    if !plugin.keywords.is_empty() {
        manifest.insert("keywords".into(), serde_json::json!(plugin.keywords));
    }
    manifest
}

fn json_file(value: &serde_json::Value) -> Result<String> {
    Ok(format!("{}\n", serde_json::to_string_pretty(value)?))
}

/// The manifest of `plugin` in this format.
fn manifest(plugin: &NormalizedPlugin, shape: &PluginShape) -> Result<String> {
    use serde_json::Value;
    let mut manifest = match shape.format {
        // Claude Code wants `author` as an object, Antigravity takes a string.
        BundleFormat::Claude | BundleFormat::Vibe | BundleFormat::Codex => {
            manifest_metadata(plugin, true)
        }
        BundleFormat::Antigravity => manifest_metadata(plugin, false),
    };
    match shape.format {
        // Codex's switch is `[plugins."<plugin>@<marketplace>"] enabled` in
        // `.codex/config.toml`, written by the Codex adapter.
        BundleFormat::Codex => {
            manifest.insert("$schema".into(), Value::String(AGENT_PLUGINS_SCHEMA.into()));
        }
        BundleFormat::Claude => {
            if plugin.disabled {
                manifest.insert("defaultEnabled".into(), Value::Bool(false));
            }
        }
        BundleFormat::Vibe => {
            manifest.insert("$schema".into(), Value::String(AGENT_PLUGINS_SCHEMA.into()));
            // "Without the `ai.mistral.vibe` extension, Vibe loads only
            // `skills/` and `mcp.json`": its subagents and hooks need the block.
            let hooks =
                crate::hooks::vibe_toml(&plugin.hooks, &format!("plugin {}", plugin.name)).0;
            if !plugin.agents.is_empty() || hooks.is_some() {
                manifest.insert(
                    "extensions".into(),
                    serde_json::json!({ "ai.mistral.vibe": { "schemaVersion": 1 } }),
                );
            }
        }
        BundleFormat::Antigravity => {
            manifest.insert("$schema".into(), Value::String(ANTIGRAVITY_SCHEMA.into()));
            if plugin.disabled {
                manifest.insert("disabled".into(), Value::Bool(true));
            }
        }
    }
    json_file(&Value::Object(manifest))
}

/// A `{"mcpServers": {...}}` file, with `$schema` first when given.
fn mcp_file(
    servers: serde_json::Map<String, serde_json::Value>,
    schema: Option<&str>,
) -> Result<String> {
    let mut file = serde_json::Map::new();
    if let Some(schema) = schema {
        file.insert("$schema".into(), serde_json::Value::String(schema.into()));
    }
    file.insert("mcpServers".into(), serde_json::Value::Object(servers));
    json_file(&serde_json::Value::Object(file))
}

/// The bundle files of `plugins` for a tool of `shape`: per plugin, its
/// folder holding conforme's marker, the manifest, its components in the
/// tool's layout and its loose files. A folder written by hand is left
/// alone (see [`bundle_warnings`]).
pub fn generate_plugins(
    project_root: &Path,
    plugins: &[NormalizedPlugin],
    shape: &PluginShape,
) -> Result<Vec<(PathBuf, String)>> {
    let mut files = Vec::new();
    for plugin in plugins {
        let bundle = bundle_dir(project_root, shape, &plugin.name);
        if is_hand_written_bundle(&bundle) {
            continue;
        }
        files.push((
            bundle.join(PLUGIN_MARKER),
            PLUGIN_MARKER_CONTENT.to_string(),
        ));
        files.push((
            join_rel(&bundle, shape.manifest()),
            manifest(plugin, shape)?,
        ));
        let skills_dir = bundle.join("skills");
        match shape.format {
            BundleFormat::Claude => {
                files.extend(crate::skills::generate_skills_in(
                    &skills_dir,
                    &plugin.skills,
                    &crate::skills::CLAUDE_SKILLS,
                )?);
                files.extend(crate::skills::generate_claude_agents_in(
                    &bundle.join("agents"),
                    &plugin.agents,
                )?);
                if !plugin.mcp_servers.is_empty() {
                    files.push((
                        bundle.join(".mcp.json"),
                        mcp_file(crate::mcp::CLAUDE_SHAPE.build(&plugin.mcp_servers), None)?,
                    ));
                }
                // `hooks/hooks.json`: "The top-level `hooks` wrapper is
                // required" (https://code.claude.com/docs/en/plugins/components.md).
                if !plugin.hooks.is_empty() {
                    files.push((
                        join_rel(&bundle, "hooks/hooks.json"),
                        json_file(
                            &serde_json::json!({ "hooks": crate::hooks::claude_json(&plugin.hooks) }),
                        )?,
                    ));
                }
            }
            BundleFormat::Vibe => {
                files.extend(crate::skills::generate_skills_in(
                    &skills_dir,
                    &plugin.skills,
                    &crate::skills::VIBE_SKILLS,
                )?);
                // A plugin subagent also declares its schema version.
                for (path, content) in crate::skills::generate_vibe_agents_in(
                    &join_rel(&bundle, "ai.mistral.vibe/agents"),
                    &plugin.agents,
                )? {
                    files.push((path, format!("schema_version = 1\n{content}")));
                }
                if !plugin.mcp_servers.is_empty() {
                    files.push((
                        bundle.join("mcp.json"),
                        mcp_file(
                            crate::mcp::AGENT_PLUGINS_SHAPE.build(&plugin.mcp_servers),
                            Some(crate::mcp::AGENT_PLUGINS_MCP_SCHEMA),
                        )?,
                    ));
                }
                if let (Some(hooks), _) =
                    crate::hooks::vibe_toml(&plugin.hooks, &format!("plugin {}", plugin.name))
                {
                    files.push((join_rel(&bundle, "ai.mistral.vibe/hooks.toml"), hooks));
                }
            }
            BundleFormat::Antigravity => {
                files.extend(crate::skills::generate_skills_in(
                    &skills_dir,
                    &plugin.skills,
                    &crate::skills::PLUGIN_SKILLS,
                )?);
                files.extend(crate::adapters::antigravity::generate_agents_in(
                    &bundle.join("agents"),
                    &plugin.agents,
                )?);
                let rules_dir = bundle.join("rules");
                files.extend(crate::adapters::antigravity::generate_rules_in(
                    &rules_dir,
                    &plugin.rules,
                )?);
                if !plugin.instructions.trim().is_empty() {
                    files.push((
                        rules_dir.join("AGENTS.md"),
                        format!("{}\n", plugin.instructions.trim()),
                    ));
                }
                if !plugin.mcp_servers.is_empty() {
                    files.push((
                        bundle.join("mcp_config.json"),
                        mcp_file(
                            crate::mcp::ANTIGRAVITY_SHAPE.build(&plugin.mcp_servers),
                            None,
                        )?,
                    ));
                }
                if let (Some(hooks), _) = crate::hooks::antigravity_json(
                    &plugin.hooks,
                    &format!("plugin {}", plugin.name),
                ) {
                    files.push((bundle.join("hooks.json"), json_file(&hooks)?));
                }
            }
            BundleFormat::Codex => {
                files.extend(crate::skills::generate_skills_in(
                    &skills_dir,
                    &plugin.skills,
                    &crate::skills::PLUGIN_SKILLS,
                )?);
                // "Don't just rename `.mcp.json`": the Agent Plugins file
                // carries its `$schema` and a `type` per server.
                if !plugin.mcp_servers.is_empty() {
                    files.push((
                        bundle.join("mcp.json"),
                        mcp_file(
                            crate::mcp::AGENT_PLUGINS_SHAPE.build(&plugin.mcp_servers),
                            Some(crate::mcp::AGENT_PLUGINS_MCP_SCHEMA),
                        )?,
                    ));
                }
            }
        }
        for (rel, content) in &plugin.files {
            files.push((join_rel(&bundle, rel), content.clone()));
        }
    }
    Ok(files)
}

/// What a tool of `shape` will not get of `config`'s plugins as written: a
/// plugin whose bundle folder was written by hand.
pub fn bundle_warnings(
    project_root: &Path,
    config: &NormalizedConfig,
    shape: &PluginShape,
) -> Vec<String> {
    let mut warnings: Vec<String> = config
        .plugins
        .iter()
        .filter(|p| is_hand_written_bundle(&bundle_dir(project_root, shape, &p.name)))
        .map(|p| {
            format!(
                "plugin {} is not written: {}/{} holds a bundle conforme did not write \
                 (no {PLUGIN_MARKER} marker); delete it to let sync write the plugin",
                p.name,
                shape.dir,
                sanitize_name(&p.name)
            )
        })
        .collect();
    for plugin in config.plugins.iter().filter(|p| !p.hooks.is_empty()) {
        match shape.format {
            BundleFormat::Vibe => {
                warnings.extend(
                    crate::hooks::vibe_toml(&plugin.hooks, &format!("plugin {}", plugin.name)).1,
                );
                warnings.push(crate::hooks::payload_warning(
                    &format!("plugin {}", plugin.name),
                    "Vibe",
                    "a hook blocks only by printing a `deny` decision (a non-zero exit is a \
                     warning unless `strict`)",
                ));
            }
            BundleFormat::Antigravity => {
                warnings.extend(
                    crate::hooks::antigravity_json(
                        &plugin.hooks,
                        &format!("plugin {}", plugin.name),
                    )
                    .1,
                );
                warnings.push(crate::hooks::payload_warning(
                    &format!("plugin {}", plugin.name),
                    "Antigravity",
                    "a hook blocks only by printing a `decision` (no exit code blocks)",
                ));
            }
            BundleFormat::Claude | BundleFormat::Codex => {}
        }
    }
    warnings
}

/// The hooks of a bundle, in its format; a hooks file that does not parse is
/// one the tool skips.
fn read_bundle_hooks(bundle: &Path, format: BundleFormat) -> Vec<crate::config::NormalizedHook> {
    let json = |rel: &str| {
        crate::config::read_text(&join_rel(bundle, rel))
            .ok()
            .and_then(|text| crate::json_settings::parse_jsonc(&text).ok())
    };
    match format {
        BundleFormat::Claude => json("hooks/hooks.json")
            .and_then(|doc| doc.get("hooks").cloned())
            .map(|hooks| crate::hooks::read_claude(&hooks))
            .unwrap_or_default(),
        BundleFormat::Vibe => {
            crate::config::read_text(&join_rel(bundle, "ai.mistral.vibe/hooks.toml"))
                .ok()
                .and_then(|text| crate::hooks::read_vibe(&text).ok())
                .unwrap_or_default()
        }
        BundleFormat::Antigravity => json("hooks.json")
            .map(|doc| crate::hooks::read_antigravity(&doc))
            .unwrap_or_default(),
        BundleFormat::Codex => Vec::new(),
    }
}

/// A text field of a manifest.
fn text_field(manifest: &serde_json::Value, key: &str) -> Option<String> {
    manifest
        .get(key)
        .and_then(serde_json::Value::as_str)
        .map(str::trim)
        .filter(|v| !v.is_empty())
        .map(str::to_string)
}

/// The plugin bundles a tool of `shape` loads from the project: every folder
/// of its bundle directory holding a manifest it reads (a manifest that does
/// not parse is one it skips). `enabled` overrides a manifest's own state
/// (Claude Code `enabledPlugins`, Vibe `disabled_plugins`), by plugin name.
pub fn read_plugins(
    project_root: &Path,
    shape: &PluginShape,
    enabled: &dyn Fn(&str) -> Option<bool>,
) -> Result<Vec<NormalizedPlugin>> {
    let root = shape.root(project_root);
    if !root.is_dir() {
        return Ok(Vec::new());
    }
    let mut folders: Vec<PathBuf> = std::fs::read_dir(&root)?
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| crate::adapters::is_real_dir(p))
        .collect();
    folders.sort();
    let mut plugins = Vec::new();
    for bundle in folders {
        let Some(manifest_path) = shape
            .manifests_read()
            .iter()
            .map(|m| join_rel(&bundle, m))
            .find(|p| p.is_file())
        else {
            continue;
        };
        let Ok(manifest) = crate::config::read_text(&manifest_path)
            .and_then(|text| Ok(serde_json::from_str::<serde_json::Value>(&text)?))
        else {
            continue;
        };
        let folder_name = bundle
            .file_name()
            .unwrap_or_default()
            .to_string_lossy()
            .to_string();
        let name = text_field(&manifest, "name").unwrap_or(folder_name);
        let author = match manifest.get("author") {
            Some(serde_json::Value::String(author)) => Some(author.trim().to_string()),
            Some(author) => text_field(author, "name"),
            None => None,
        }
        .filter(|a| !a.is_empty());
        let manifest_disabled = match shape.format {
            BundleFormat::Claude => {
                manifest
                    .get("defaultEnabled")
                    .and_then(serde_json::Value::as_bool)
                    == Some(false)
            }
            BundleFormat::Antigravity => {
                manifest
                    .get("disabled")
                    .and_then(serde_json::Value::as_bool)
                    == Some(true)
            }
            // Their switch lives in the tool's config (`enabled`).
            BundleFormat::Vibe | BundleFormat::Codex => false,
        };
        let mut plugin = NormalizedPlugin {
            description: text_field(&manifest, "description").unwrap_or_default(),
            version: text_field(&manifest, "version"),
            author,
            homepage: text_field(&manifest, "homepage"),
            repository: text_field(&manifest, "repository"),
            license: text_field(&manifest, "license"),
            keywords: manifest
                .get("keywords")
                .and_then(serde_json::Value::as_array)
                .map(|k| {
                    k.iter()
                        .filter_map(|v| v.as_str().map(str::to_string))
                        .collect()
                })
                .unwrap_or_default(),
            disabled: enabled(&name).map_or(manifest_disabled, |on| !on),
            name,
            ..Default::default()
        };
        plugin.skills = crate::skills::read_skills_from_dir(&bundle.join("skills"))?;
        let mcp_file = match shape.format {
            BundleFormat::Claude => {
                let commands = crate::adapters::claude::read_commands_in(
                    &bundle.join("commands"),
                    &plugin.skills,
                )?;
                plugin.skills.extend(commands);
                plugin.agents = crate::adapters::claude::read_agents_in(&bundle.join("agents"))?;
                Some((bundle.join(".mcp.json"), &crate::mcp::CLAUDE_SHAPE))
            }
            BundleFormat::Vibe => {
                let agents_dir = join_rel(&bundle, "ai.mistral.vibe/agents");
                if agents_dir.is_dir() {
                    plugin.agents = crate::skills::read_vibe_agents_in(
                        &agents_dir,
                        &join_rel(&bundle, "ai.mistral.vibe/prompts"),
                    )?;
                }
                Some((bundle.join("mcp.json"), &crate::mcp::AGENT_PLUGINS_SHAPE))
            }
            BundleFormat::Codex => {
                Some((bundle.join("mcp.json"), &crate::mcp::AGENT_PLUGINS_SHAPE))
            }
            BundleFormat::Antigravity => {
                plugin.agents =
                    crate::adapters::antigravity::read_agents_in(&bundle.join("agents"))?;
                let rules_dir = bundle.join("rules");
                plugin.rules = crate::adapters::antigravity::read_rules_in(&rules_dir)?;
                let instructions = rules_dir.join("AGENTS.md");
                if instructions.is_file() {
                    plugin.instructions =
                        crate::config::read_text(&instructions)?.trim().to_string();
                }
                Some((
                    bundle.join("mcp_config.json"),
                    &crate::mcp::ANTIGRAVITY_SHAPE,
                ))
            }
        };
        if let Some((path, server_shape)) = mcp_file.filter(|(path, _)| path.is_file()) {
            plugin.mcp_servers = server_shape.read_file(&crate::config::read_text(&path)?)?;
        }
        plugin.hooks = read_bundle_hooks(&bundle, shape.format);
        let components: Vec<PathBuf> = shape
            .component_paths()
            .iter()
            .map(|c| join_rel(&bundle, c))
            .collect();
        for path in files_under(&bundle)? {
            let is_component = components.iter().any(|c| path.starts_with(c));
            let name = path.file_name().unwrap_or_default().to_string_lossy();
            let litter = name == ".DS_Store" || name.ends_with('~') || name.ends_with(".swp");
            if is_component || litter || path == bundle.join(PLUGIN_MARKER) {
                continue;
            }
            if let Ok(content) = std::fs::read_to_string(&path) {
                let rel = path
                    .strip_prefix(&bundle)
                    .unwrap_or(&path)
                    .components()
                    .map(|c| c.as_os_str().to_string_lossy().to_string())
                    .collect::<Vec<_>>()
                    .join("/");
                plugin.files.insert(rel, content);
            }
        }
        plugins.push(plugin);
    }
    Ok(plugins)
}

/// The variables a plugin's files use to reach the bundle's own folder
/// (`${CLAUDE_PLUGIN_ROOT}/scripts/check.sh`) or its data folder. They mean
/// nothing outside a loaded bundle.
const ROOT_VARIABLES: &[&str] = &[
    "${PLUGIN_ROOT}",
    "${PLUGIN_DATA}",
    "${CLAUDE_PLUGIN_ROOT}",
    "${CLAUDE_PLUGIN_DATA}",
    "${CURSOR_PLUGIN_ROOT}",
    "${COPILOT_PLUGIN_ROOT}",
];

/// Whether `text` reaches into the plugin's own folder.
pub fn uses_plugin_root(text: &str) -> bool {
    ROOT_VARIABLES.iter().any(|var| text.contains(var))
}

/// The names already taken in the flattened config, per kind, compared the
/// way each kind is written to disk.
struct Taken {
    rules: HashSet<String>,
    skills: HashSet<String>,
    agents: HashSet<String>,
    servers: HashSet<String>,
}

/// A free name for `name` from plugin `plugin`: the name itself, else
/// `<plugin>-<name>`; `None` when both are taken.
fn free_name(
    taken: &mut HashSet<String>,
    key: fn(&str) -> String,
    plugin: &str,
    name: &str,
) -> Option<String> {
    let prefixed = format!("{plugin}-{name}");
    [name.to_string(), prefixed]
        .into_iter()
        .find(|candidate| !taken.contains(&key(candidate)))
        .inspect(|candidate| {
            taken.insert(key(candidate));
        })
}

fn same(name: &str) -> String {
    name.to_string()
}

/// Place one item of `plugin` under a free name, or report it skipped.
fn place(
    taken: &mut HashSet<String>,
    key: fn(&str) -> String,
    plugin: &NormalizedPlugin,
    kind: &str,
    name: &str,
    warnings: &mut Vec<String>,
) -> Option<String> {
    let placed = free_name(taken, key, &plugin.name, name);
    match &placed {
        None => warnings.push(format!(
            "plugin {}: {kind} {name} is left out: the project already has a {kind} named \
             {name} and one named {}-{name}",
            plugin.name, plugin.name
        )),
        Some(placed) if placed != name => warnings.push(format!(
            "plugin {}: {kind} {name} is written as {placed}, since the project already has \
             a {kind} named {name}",
            plugin.name
        )),
        Some(_) => {}
    }
    placed
}

/// The config with every plugin's content moved into the top-level rules,
/// skills, agents and MCP servers, for a tool that cannot hold a plugin
/// bundle, and the warnings about what that loses:
///
/// - a plugin's instructions become an always-on rule named after it;
/// - an item keeps its name, or becomes `<plugin>-<name>` when the project
///   (or an earlier plugin) already has one of that name, and is left out
///   when both are taken;
/// - an item that uses `${PLUGIN_ROOT}`-style variables (see
///   [`uses_plugin_root`]) only works inside the bundle and is left out;
/// - a disabled plugin is left out whole: a tool without bundles has no
///   switch to keep it off;
/// - the bundle's loose files have no place outside it.
///
/// A plugin with an empty name, or two plugins of the same name, are an
/// error.
pub fn flatten(config: &NormalizedConfig) -> Result<(NormalizedConfig, Vec<String>)> {
    let mut out = config.clone();
    if config.plugins.is_empty() {
        return Ok((out, Vec::new()));
    }
    out.plugins.clear();
    let mut warnings = Vec::new();
    let mut taken = Taken {
        rules: config
            .rules
            .iter()
            .map(|r| rule_file_name(&r.name))
            .collect(),
        skills: config
            .skills
            .iter()
            .map(|s| sanitize_name(&s.name))
            .collect(),
        agents: config
            .agents
            .iter()
            .map(|a| sanitize_name(&a.name))
            .collect(),
        servers: config.mcp_servers.iter().map(|m| m.name.clone()).collect(),
    };
    let mut plugin_names = HashSet::new();
    for plugin in &config.plugins {
        let key = sanitize_name(&plugin.name);
        if key.is_empty() {
            bail!(
                "plugin {:?} has no usable name: a plugin name needs at least one letter or digit",
                plugin.name
            );
        }
        if !plugin_names.insert(key) {
            bail!("plugin {} is defined twice", plugin.name);
        }
        if plugin.disabled {
            if !plugin.is_empty() {
                warnings.push(format!(
                    "plugin {} is disabled, so tools that cannot hold a plugin bundle do not \
                     get its content",
                    plugin.name
                ));
            }
            continue;
        }
        if !plugin.hooks.is_empty() {
            let names: Vec<&str> = plugin.hooks.iter().map(|h| h.name.as_str()).collect();
            warnings.push(format!(
                "plugin {}: its hooks ({}) run only in tools that hold plugin bundles with hooks \
                 (Claude Code, Mistral Vibe, Antigravity CLI)",
                plugin.name,
                names.join(", ")
            ));
        }
        if !plugin.files.is_empty() {
            let files: Vec<&str> = plugin.files.keys().map(String::as_str).collect();
            warnings.push(format!(
                "plugin {}: its bundled files ({}) only exist inside a plugin bundle",
                plugin.name,
                files.join(", ")
            ));
        }
        let skipped = |kind: &str, name: &str, warnings: &mut Vec<String>| {
            warnings.push(format!(
                "plugin {}: {kind} {name} is left out: it uses the plugin's own folder \
                 (${{PLUGIN_ROOT}}), which only exists inside a plugin bundle",
                plugin.name
            ));
        };

        let mut rules = Vec::new();
        if !plugin.instructions.trim().is_empty() {
            rules.push(NormalizedRule {
                name: plugin.name.clone(),
                content: plugin.instructions.clone(),
                activation: ActivationMode::Always,
            });
        }
        rules.extend(plugin.rules.iter().cloned());
        for mut rule in rules {
            if uses_plugin_root(&rule.content) {
                skipped("rule", &rule.name, &mut warnings);
                continue;
            }
            let Some(name) = place(
                &mut taken.rules,
                rule_file_name,
                plugin,
                "rule",
                &rule.name,
                &mut warnings,
            ) else {
                continue;
            };
            rule.name = name;
            out.rules.push(rule);
        }

        for skill in &plugin.skills {
            if uses_plugin_root(&skill.content) || skill.files.values().any(|f| uses_plugin_root(f))
            {
                skipped("skill", &skill.name, &mut warnings);
                continue;
            }
            let Some(name) = place(
                &mut taken.skills,
                sanitize_name,
                plugin,
                "skill",
                &skill.name,
                &mut warnings,
            ) else {
                continue;
            };
            out.skills.push(crate::config::NormalizedSkill {
                name,
                ..skill.clone()
            });
        }

        for agent in &plugin.agents {
            if uses_plugin_root(&agent.content) {
                skipped("agent", &agent.name, &mut warnings);
                continue;
            }
            let Some(name) = place(
                &mut taken.agents,
                sanitize_name,
                plugin,
                "agent",
                &agent.name,
                &mut warnings,
            ) else {
                continue;
            };
            out.agents.push(crate::config::NormalizedAgent {
                name,
                ..agent.clone()
            });
        }

        for server in &plugin.mcp_servers {
            if crate::mcp::server_strings(server)
                .iter()
                .any(|(_, value)| uses_plugin_root(value))
            {
                skipped("MCP server", &server.name, &mut warnings);
                continue;
            }
            let Some(name) = place(
                &mut taken.servers,
                same,
                plugin,
                "MCP server",
                &server.name,
                &mut warnings,
            ) else {
                continue;
            };
            out.mcp_servers.push(crate::config::NormalizedMcpServer {
                name,
                ..server.clone()
            });
        }
    }
    Ok((out, warnings))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{McpTransport, NormalizedMcpServer, NormalizedSkill};

    fn skill(name: &str, content: &str) -> NormalizedSkill {
        NormalizedSkill {
            name: name.to_string(),
            description: format!("{name} skill"),
            content: content.to_string(),
            ..Default::default()
        }
    }

    fn plugin(name: &str) -> NormalizedPlugin {
        NormalizedPlugin {
            name: name.to_string(),
            ..Default::default()
        }
    }

    #[test]
    fn test_flatten_moves_every_component_to_the_top_level() {
        let mut demo = plugin("demo");
        demo.instructions = "Always be kind.".to_string();
        demo.skills.push(skill("lint", "Run the linter."));
        demo.agents.push(crate::config::NormalizedAgent {
            name: "reviewer".to_string(),
            content: "Review.".to_string(),
            ..Default::default()
        });
        demo.mcp_servers.push(NormalizedMcpServer {
            name: "docs".to_string(),
            transport: McpTransport::Http {
                url: "https://example.com/mcp".to_string(),
                headers: Default::default(),
            },
            env: Default::default(),
        });
        let config = NormalizedConfig {
            plugins: vec![demo],
            ..Default::default()
        };

        let (flat, warnings) = flatten(&config).unwrap();

        assert!(warnings.is_empty(), "{warnings:?}");
        assert!(flat.plugins.is_empty());
        assert_eq!(flat.rules[0].name, "demo");
        assert_eq!(flat.rules[0].activation, ActivationMode::Always);
        assert_eq!(flat.skills[0].name, "lint");
        assert_eq!(flat.agents[0].name, "reviewer");
        assert_eq!(flat.mcp_servers[0].name, "docs");
    }

    #[test]
    fn test_flatten_prefixes_a_taken_name_then_leaves_it_out() {
        let mut demo = plugin("demo");
        demo.skills.push(skill("lint", "Plugin lint."));
        let config = NormalizedConfig {
            skills: vec![skill("lint", "Project lint.")],
            plugins: vec![demo.clone()],
            ..Default::default()
        };
        let (flat, warnings) = flatten(&config).unwrap();
        let names: Vec<_> = flat.skills.iter().map(|s| s.name.as_str()).collect();
        assert_eq!(names, ["lint", "demo-lint"]);
        assert!(warnings[0].contains("written as demo-lint"), "{warnings:?}");

        let config = NormalizedConfig {
            skills: vec![skill("lint", "A."), skill("demo-lint", "B.")],
            plugins: vec![demo],
            ..Default::default()
        };
        let (flat, warnings) = flatten(&config).unwrap();
        assert_eq!(flat.skills.len(), 2);
        assert!(warnings[0].contains("left out"), "{warnings:?}");
    }

    #[test]
    fn test_flatten_leaves_out_items_using_the_plugin_root() {
        let mut demo = plugin("demo");
        demo.skills.push(skill(
            "check",
            "Run ${CLAUDE_PLUGIN_ROOT}/scripts/check.sh.",
        ));
        demo.mcp_servers.push(NormalizedMcpServer {
            name: "local".to_string(),
            transport: McpTransport::Stdio {
                command: "node".to_string(),
                args: vec!["${PLUGIN_ROOT}/server.js".to_string()],
            },
            env: Default::default(),
        });
        let config = NormalizedConfig {
            plugins: vec![demo],
            ..Default::default()
        };
        let (flat, warnings) = flatten(&config).unwrap();
        assert!(flat.skills.is_empty() && flat.mcp_servers.is_empty());
        assert_eq!(warnings.len(), 2, "{warnings:?}");
    }

    #[test]
    fn test_flatten_skips_a_disabled_plugin_and_refuses_duplicates() {
        let mut off = plugin("off");
        off.disabled = true;
        off.skills.push(skill("x", "X."));
        let config = NormalizedConfig {
            plugins: vec![off],
            ..Default::default()
        };
        let (flat, warnings) = flatten(&config).unwrap();
        assert!(flat.skills.is_empty());
        assert!(warnings[0].contains("disabled"));

        let config = NormalizedConfig {
            plugins: vec![plugin("Demo"), plugin("demo")],
            ..Default::default()
        };
        assert!(flatten(&config).is_err());
        let config = NormalizedConfig {
            plugins: vec![plugin("!!")],
            ..Default::default()
        };
        assert!(flatten(&config).is_err());
    }
}
